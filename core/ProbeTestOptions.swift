import Foundation

enum ProbeTestOptions {
    /// 测试服：发版前全局搜索“测试服”，并确认这里恢复为空集合。
    /// 多节点探测测试，仅修改交给 `pingBatch` 的内存配置副本：
    /// 命中的节点会把 proxy 端口临时改为 1，使该节点真实探测失败。
    /// 接口响应、最终配置、App Group 数据和成功缓存都不会被修改。
    ///
    /// 节点按接口 `res` 数组从 0 开始编号：0 是第一个节点，1 是第二个节点，以此类推。
    /// 常用测试情况：
    /// - `[]`：关闭测试，全部节点使用真实配置。
    /// - `[0]`：第一个节点失败，应继续尝试第二个节点。
    /// - `[1]`：第二个节点失败；如果第一个节点成功，仍选择第一个节点。
    /// - `[0, 1]`：前两个节点失败，应继续尝试第三个节点。
    /// - `[0, 2]`：第一个、第三个节点失败，应优先选择第二个成功节点。
    /// - `[1, 2]`：第二个、第三个节点失败，应优先选择第一个成功节点。
    /// - `[0, 1, 2]`：前三个节点失败；若接口只有三个节点，最终连接失败。
    /// - `[0, 1, 2, 3, 4]`：最多五个节点全部失败，最终连接失败。
    ///
    /// 测试结束后必须恢复为 `[]`。
    static let unreachableNodePositions: Set<Int> = []
}
